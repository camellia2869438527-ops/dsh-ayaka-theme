import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sources = ['palette.js', 'controller.js', 'art.js', 'client.js'].map(name =>
  fs.readFileSync(path.join(root, 'src', name), 'utf8')
    .replace(/^import .*;\r?\n/gm, '')
    .replace(/^export /gm, ''),
);
const css = fs.readFileSync(path.join(root, 'src/card.css'), 'utf8');

// Assets are served by the host route (lib/index.js) rather than inlined, so a
// 15-second video and 11 stickers stay streamable and the package stays small.
const ASSETS = {
  video: '/dsh-ayaka-theme/assets/video.mp4',
  poster: '/dsh-ayaka-theme/assets/poster.jpg',
  stickers: Array.from({ length: 11 }, (_, i) => `/dsh-ayaka-theme/assets/stickers/${i}.webp`),
};

const code = `// Generated by scripts/build.mjs. DSH lazy factory; no runtime dependencies.\nwindow.__ModuleLoader__.load({id:'dsh-ayaka-theme',factory:(require)=>{\n'use strict';\nconst React=require('react');\nconst ASSETS=${JSON.stringify(ASSETS)};\n${sources.join('\n')}\nreturn {inject,apply:ctx=>applyClient(ctx,React,${JSON.stringify(css)},ASSETS)};\n}});\n`;

fs.mkdirSync(path.join(root, 'lib'), { recursive: true });
fs.writeFileSync(path.join(root, 'lib/client.js'), code);
console.log('Built lib/client.js (' + Buffer.byteLength(code) + ' bytes)');
